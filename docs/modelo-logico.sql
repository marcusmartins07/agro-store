/*
 * Modelo lógico canônico do Agro Store — MODELO-ALVO (PostgreSQL), versão 2.4.
 * A versão 2.4 alinha loja.id_proprietario aos models (DB-003/DB-014, RN-013,
 * migration lojas/0003): uma loja por produtor (uq_loja_proprietario) e
 * RESTRICT/PROTECT; o DDL de loja não muda.
 * A versão 2.3 torna avaliacao.id_produto opcional com ON DELETE SET NULL
 * (DB-015): excluir o produto preserva a avaliação ligada ao item do pedido.
 * A versão 2.1 acrescenta redefinicao_senha (DB-017, RN-020). A versão 2.2
 * acrescenta tipo_telefone e telefone (DB-018, RN-021) e remove as colunas
 * usuario.telefone e pedido_cliente.telefone: o telefone deixa de fazer parte
 * do snapshot do pedido. O diagrama 2.1 (docs/diagramas-banco) usa NUMERIC
 * para o número do telefone; aqui ele é texto, preservando zeros à esquerda.
 * A coluna usuario.foto_perfil (DB-011,
 * RN-018; migration usuarios/0004) foi incluída na conferência da DOC-022,
 * no mesmo padrão de loja.imagem_perfil ('' quando vazia).
 *
 * ATENÇÃO: este arquivo descreve o modelo-alvo, NÃO o schema atual. O schema
 * executável é gerado pelas migrations do Django (SQLite em desenvolvimento).
 * Alterações neste arquivo não autorizam, por si só, mudanças em models,
 * migrations ou API: o alinhamento exige tarefa própria e aprovação.
 *
 * Divergências conhecidas com os models atuais (alinhamento na DB-009):
 *
 * 1. on_delete: os models usam CASCADE onde este modelo usa RESTRICT em
 *    produto.id_loja, preco_produto.id_produto e em duas FKs de avaliacao
 *    (id_usuario, id_pedido_produto).
 * 2. Nomes físicos: tabelas e colunas aqui seguem o padrão em português
 *    (id_<entidade>, esta_ativo, senha, valor_venda, imagem.caminho etc.);
 *    os models ainda usam os nomes gerados pelo Django (id, ativo, password,
 *    preco_venda, produtos_imagemproduto.imagem etc.).
 * 3. Restrições que só existem neste modelo:
 *    CHECK (estoque >= 0), sku NOT NULL, uq_imagem_produto_ordem
 *    (id_produto, ordem), ck_avaliacao_comentario_tamanho e os demais CHECK
 *    de valores (preço, carrinho, pedido) e de vigência (ck_preco_vigencia);
 *    fora de redefinicao_senha e pedido_produto, os models não declaram
 *    CheckConstraint.
 *
 * pedido_produto está alinhado aos models (DB-015, migration pedidos/0007):
 * id_produto é opcional com SET NULL, e os CHECK de quantidade (> 0),
 * valor_unitario, valor_desconto e subtotal (>= 0) existem no model como
 * pedido_produto_quantidade_positiva, pedido_produto_valor_unitario_nao_negativo,
 * pedido_produto_valor_desconto_nao_negativo e
 * pedido_produto_subtotal_nao_negativo. avaliacao.id_produto passou a ser
 * opcional com ON DELETE SET NULL (DB-015, migration avaliacoes/0002): a
 * avaliação continua ligada ao item do pedido (id_pedido_produto), que guarda
 * o snapshot do produto. O Django não gera ON DELETE no banco: SET NULL é
 * executado pelo ORM, e a FK física fica sem ação (NO ACTION).
 *
 * A restrição ck_redefinicao_senha_expiracao existe no model
 * (redefinicao_senha_expiracao_apos_criacao, migration usuarios/0005).
 * A restrição de imagem principal única por produto existe no model
 * (imagem_principal_unica_por_produto) e está refletida neste arquivo.
 * A restrição de telefone principal único por usuário existe no model
 * (telefone_principal_unico_por_usuario, migration usuarios/0006) e está
 * refletida neste arquivo.
 * loja.id_proprietario está alinhado desde a migration lojas/0003 (DB-003/DB-014):
 * o model tem uq_loja_proprietario e PROTECT, equivalente ao RESTRICT daqui.
 */

CREATE TABLE genero (
    codigo_genero VARCHAR(2) PRIMARY KEY,
    nome VARCHAR(55) NOT NULL UNIQUE
);

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    email VARCHAR(254) NOT NULL UNIQUE,
    data_nascimento DATE NOT NULL,
    foto_perfil VARCHAR(255) NOT NULL DEFAULT '',
    senha VARCHAR(128) NOT NULL,
    ultimo_login TIMESTAMP WITH TIME ZONE,
    e_produtor BOOLEAN NOT NULL DEFAULT FALSE,
    esta_ativo BOOLEAN NOT NULL DEFAULT TRUE,
    e_equipe BOOLEAN NOT NULL DEFAULT FALSE,
    e_superusuario BOOLEAN NOT NULL DEFAULT FALSE,
    codigo_genero VARCHAR(2) NOT NULL,
    CONSTRAINT fk_usuario_genero
        FOREIGN KEY (codigo_genero) REFERENCES genero (codigo_genero)
        ON DELETE RESTRICT
);

-- RN-020: só o hash do token é salvo; validade de 30 minutos e uso único.
-- data_utilizacao NULL = pendente; preenchida = usada ou invalidada por um
-- novo pedido ou por uma troca bem-sucedida. O histórico é preservado
-- enquanto o usuário existir (CASCADE: só usuário sem pedidos é excluído).
CREATE TABLE redefinicao_senha (
    id_redefinicao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    data_expiracao TIMESTAMP WITH TIME ZONE NOT NULL,
    data_utilizacao TIMESTAMP WITH TIME ZONE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_redefinicao_senha_expiracao CHECK (data_expiracao > data_criacao),
    CONSTRAINT fk_redefinicao_senha_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
        ON DELETE CASCADE
);

-- RN-021: tipos fixos (Celular, Fixo, Comercial), carregados por migration
-- (usuarios/0007); não são cadastrados pelo usuário.
CREATE TABLE tipo_telefone (
    id_tipo_telefone BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    descricao VARCHAR(30) NOT NULL UNIQUE
);

-- RN-021: usuário (1,1) — (0,n) telefone. Número somente com dígitos, com DDD,
-- sem unicidade entre usuários. O mínimo de 1 telefone e a quantidade de
-- dígitos por tipo (Celular 11, Fixo 10, Comercial 10 ou 11) são validados na
-- API e no admin. Exceção legada: contas sem telefone antes da DB-018 e contas
-- criadas por createsuperuser podem ter 0 telefones.
CREATE TABLE telefone (
    id_telefone BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_tipo_telefone BIGINT NOT NULL,
    numero VARCHAR(11) NOT NULL,
    e_principal BOOLEAN NOT NULL DEFAULT FALSE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_telefone_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_telefone_tipo_telefone
        FOREIGN KEY (id_tipo_telefone) REFERENCES tipo_telefone (id_tipo_telefone)
        ON DELETE RESTRICT
);

-- No máximo um telefone principal por usuário (RN-021). Mesmo nome da
-- UniqueConstraint condicional do model Telefone.
CREATE UNIQUE INDEX telefone_principal_unico_por_usuario
    ON telefone (id_usuario)
    WHERE e_principal;

CREATE TABLE loja (
    id_loja BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_proprietario BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT NOT NULL DEFAULT '',
    cnpj VARCHAR(14) NOT NULL UNIQUE,
    imagem_perfil VARCHAR(255) NOT NULL DEFAULT '',
    esta_ativa BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_loja_proprietario
        FOREIGN KEY (id_proprietario) REFERENCES usuario (id_usuario)
        ON DELETE RESTRICT,
    CONSTRAINT uq_loja_proprietario UNIQUE (id_proprietario)
);

CREATE TABLE categoria (
    id_categoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    esta_ativa BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE produto (
    id_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_loja BIGINT NOT NULL,
    id_categoria BIGINT NOT NULL,
    nome VARCHAR(155) NOT NULL,
    descricao TEXT NOT NULL DEFAULT '',
    codigo_barras VARCHAR(13),
    estoque INTEGER NOT NULL DEFAULT 0 CHECK (estoque >= 0),
    sku VARCHAR(50) NOT NULL UNIQUE,
    esta_ativo BOOLEAN NOT NULL DEFAULT TRUE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_produto_loja
        FOREIGN KEY (id_loja) REFERENCES loja (id_loja)
        ON DELETE RESTRICT,
    CONSTRAINT fk_produto_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria (id_categoria)
        ON DELETE RESTRICT
);

CREATE TABLE preco_produto (
    id_preco_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto BIGINT NOT NULL,
    valor_venda DECIMAL(10, 2) NOT NULL CHECK (valor_venda >= 0),
    valor_custo DECIMAL(10, 2) CHECK (valor_custo >= 0),
    valor_desconto DECIMAL(10, 2) CHECK (valor_desconto >= 0),
    porcentagem_desconto INTEGER CHECK (porcentagem_desconto BETWEEN 0 AND 100),
    vigencia_inicio TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vigencia_fim TIMESTAMP WITH TIME ZONE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_preco_produto
        FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE RESTRICT,
    CONSTRAINT ck_preco_vigencia CHECK (vigencia_fim IS NULL OR vigencia_fim >= vigencia_inicio)
);

CREATE TABLE imagem (
    id_imagem BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_produto BIGINT NOT NULL,
    caminho VARCHAR(255) NOT NULL,
    ordem INTEGER NOT NULL DEFAULT 0 CHECK (ordem >= 0),
    e_principal BOOLEAN NOT NULL DEFAULT FALSE,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_imagem_produto
        FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE CASCADE,
    CONSTRAINT uq_imagem_produto_ordem UNIQUE (id_produto, ordem)
);

-- No máximo uma imagem principal por produto (RN-016). Mesmo nome da
-- UniqueConstraint condicional do model ImagemProduto.
CREATE UNIQUE INDEX imagem_principal_unica_por_produto
    ON imagem (id_produto)
    WHERE e_principal;

CREATE TABLE carrinho (
    id_carrinho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_loja BIGINT NOT NULL,
    valor_bruto DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_bruto >= 0),
    valor_desconto DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_desconto >= 0),
    valor_liquido DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_liquido >= 0),
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_carrinho_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_carrinho_loja
        FOREIGN KEY (id_loja) REFERENCES loja (id_loja)
        ON DELETE CASCADE,
    CONSTRAINT uq_carrinho_usuario_loja UNIQUE (id_usuario, id_loja)
);

CREATE TABLE carrinho_produto (
    id_carrinho_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_carrinho BIGINT NOT NULL,
    id_produto BIGINT NOT NULL,
    -- RN-017: quantidade 0 mantém o item no carrinho como "Sem estoque".
    quantidade INTEGER NOT NULL DEFAULT 1 CHECK (quantidade >= 0),
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_carrinho_produto_carrinho
        FOREIGN KEY (id_carrinho) REFERENCES carrinho (id_carrinho)
        ON DELETE CASCADE,
    CONSTRAINT fk_carrinho_produto_produto
        FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE CASCADE,
    CONSTRAINT uq_carrinho_produto UNIQUE (id_carrinho, id_produto)
);

CREATE TABLE status_pedido (
    id_status_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(55) NOT NULL UNIQUE
);

CREATE TABLE pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_loja BIGINT NOT NULL,
    id_status_pedido BIGINT NOT NULL,
    valor_bruto DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_bruto >= 0),
    valor_desconto DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_desconto >= 0),
    valor_liquido DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_liquido >= 0),
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_loja
        FOREIGN KEY (id_loja) REFERENCES loja (id_loja)
        ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_status
        FOREIGN KEY (id_status_pedido) REFERENCES status_pedido (id_status_pedido)
        ON DELETE RESTRICT
);

CREATE TABLE pedido_cliente (
    id_pedido_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL UNIQUE,
    id_usuario BIGINT NOT NULL,
    nome VARCHAR(150) NOT NULL,
    cpf VARCHAR(11) NOT NULL,
    email VARCHAR(254) NOT NULL,
    data_nascimento DATE NOT NULL,
    genero VARCHAR(55) NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_cliente_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido)
        ON DELETE CASCADE,
    CONSTRAINT fk_pedido_cliente_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
        ON DELETE RESTRICT
);

CREATE TABLE pedido_produto (
    id_pedido_produto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    id_produto BIGINT,
    nome_produto VARCHAR(155) NOT NULL,
    quantidade INTEGER NOT NULL CHECK (quantidade > 0),
    valor_unitario DECIMAL(10, 2) NOT NULL CHECK (valor_unitario >= 0),
    valor_desconto DECIMAL(10, 2) NOT NULL DEFAULT 0 CHECK (valor_desconto >= 0),
    subtotal DECIMAL(10, 2) NOT NULL CHECK (subtotal >= 0),
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pedido_produto_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido (id_pedido)
        ON DELETE CASCADE,
    CONSTRAINT fk_pedido_produto_produto
        FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE SET NULL
);

CREATE TABLE favorito (
    id_favorito BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_produto BIGINT NOT NULL,
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_favorito_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
        ON DELETE CASCADE,
    CONSTRAINT fk_favorito_produto
        FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE CASCADE,
    CONSTRAINT uq_favorito_usuario_produto UNIQUE (id_usuario, id_produto)
);

CREATE TABLE avaliacao (
    id_avaliacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_produto BIGINT,
    id_pedido_produto BIGINT NOT NULL UNIQUE,
    nota INTEGER NOT NULL CHECK (nota BETWEEN 1 AND 5),
    comentario TEXT NOT NULL DEFAULT '',
    data_criacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    data_atualizacao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    -- RN-010: comentário opcional com até 500 caracteres.
    CONSTRAINT ck_avaliacao_comentario_tamanho CHECK (char_length(comentario) <= 500),
    CONSTRAINT fk_avaliacao_usuario
        FOREIGN KEY (id_usuario) REFERENCES usuario (id_usuario)
        ON DELETE RESTRICT,
    CONSTRAINT fk_avaliacao_produto
        FOREIGN KEY (id_produto) REFERENCES produto (id_produto)
        ON DELETE SET NULL,
    CONSTRAINT fk_avaliacao_pedido_produto
        FOREIGN KEY (id_pedido_produto) REFERENCES pedido_produto (id_pedido_produto)
        ON DELETE RESTRICT
);
